use super::*;

#[derive(Clone, Debug, PartialEq, Eq)]
pub(super) enum SidebarRow {
    Folder {
        path: String,
        depth: usize,
        count: usize,
    },
    Entry {
        index: usize,
        depth: usize,
    },
}
pub(super) struct OnboardingState {
    pub(super) path: PathBuf,
    pub(super) preview: bool,
}

pub(crate) struct AppState {
    // Store and entry browsing.
    pub(super) theme: Theme,
    pub(super) session: Session,
    pub(super) entries: Vec<Entry>,
    pub(super) filtered: Vec<usize>,
    pub(super) sidebar_rows: Vec<SidebarRow>,
    pub(super) sidebar_cursor: usize,
    pub(super) expanded_folders: HashSet<String>,
    pub(super) list_scroll: UniformListScrollHandle,
    pub(super) sidebar_scroll: sidebar_scroll::SidebarScroll,
    pub(super) query: String,
    pub(super) selection: Range<usize>,
    pub(super) marked: Option<Range<usize>>,
    pub(super) input_bounds: Option<Bounds<gpui::Pixels>>,
    pub(super) focus: FocusHandle,
    pub(super) search_focus: FocusHandle,
    pub(super) generator_name_focus: FocusHandle,
    pub(super) custom_entry_name_focus: FocusHandle,
    // Store loading, process configuration, and lifecycle.
    pub(super) generator_name: Zeroizing<String>,
    pub(super) generator_name_selection: Range<usize>,
    pub(super) generator_name_anchor: Option<usize>,
    pub(super) generator_name_cursor: usize,
    pub(super) generator_name_marked: Option<Range<usize>>,
    pub(super) generator_name_bounds: Option<Bounds<gpui::Pixels>>,
    pub(super) active: bool,
    pub(super) store: Option<Store>,
    pub(super) path: Option<PathBuf>,
    pub(super) gpg: PathBuf,
    pub(super) demo: bool,
    pub(super) demo_empty_store: bool,
    pub(super) onboarding_demo: bool,
    pub(super) preview_store_load: bool,
    pub(super) loading_demo: bool,
    pub(super) load: Option<Receiver<LoadedStore>>,
    pub(super) onboarding: Option<OnboardingState>,
    pub(super) onboarding_pending: Option<Receiver<OnboardingResult>>,
    pub(super) reveal: Option<(RevealRequest, Receiver<VersionedSecretResult>)>,
    pub(super) copy_pending: Option<PendingCopy>,
    pub(super) content_generated: bool,
    pub(super) clipboard: ClipboardState,
    pub(super) clipboard_seconds: Option<u64>,
    pub(super) generation_words: usize,
    pub(super) generator_mode: GeneratorMode,
    pub(super) generation_digits: bool,
    pub(super) generation_separators: bool,
    pub(super) generator_slider_bounds: Option<Bounds<gpui::Pixels>>,
    // Generator and custom-entry editing.
    pub(super) custom_entry_name: String,
    pub(super) custom_entry_name_selection: Range<usize>,
    pub(super) custom_entry_name_cursor: usize,
    pub(super) custom_entry_name_anchor: Option<usize>,
    pub(super) custom_entry_name_marked: Option<Range<usize>>,
    pub(super) custom_entry_name_bounds: Option<Bounds<gpui::Pixels>>,
    pub(super) navigation: Navigation,
    pub(super) confirming_delete: Option<Entry>,
    pub(super) confirming_overwrite: Option<OverwriteConfirmation>,
    pub(super) saving: Option<PendingSave>,
    // Hardware detection and device verification.
    pub(super) yubikey_history: VecDeque<YubiRecord>,
    pub(super) last_yubikey_observation: Option<Instant>,
    pub(super) yubikey_connection: YubiConnection,
    pub(super) yubikey_details: Option<CardDetails>,
    pub(super) yubikey_check: Option<CardProbe<CardProbeResult>>,
    pub(super) yubikey_last_checked: Option<Instant>,
    pub(super) yubikey_info: Option<YubiKeyInfo>,
    pub(super) yubikey_info_check: Option<CardProbe<YubiKeyInfo>>,
    pub(super) usb_reader_details: Option<UsbReaderDetails>,
    pub(super) card_detail_retry_at: Option<Instant>,
    pub(super) card_refresh: CardRefresh,
    pub(super) device_verification: DeviceVerification,
    pub(super) verification_state_seen: VerificationState,
    pub(super) verification_notification_until: Option<Instant>,
    pub(super) card_watcher: Option<CardWatcher>,
    pub(super) card_watcher_supported: Option<bool>,
    pub(super) card_watcher_retry_at: Option<Instant>,
    pub(super) card_refresh_pending: bool,
    pub(super) card_poll_paused: bool,
    pub(super) usb_card_watcher: Option<UsbCardWatcher>,
    pub(super) usb_watcher_retry_at: Option<Instant>,
    pub(super) usb_yubikey_present: Option<bool>,
    pub(super) usb_last_scan: Option<Instant>,
    // Entry editing and transient UI notifications.
    pub(super) close_after_save: bool,
    pub(super) editing_entry: bool,
    pub(super) editor_layout: Option<entry_editor::TextLayout>,
    pub(super) saving_edit: bool,
    pub(super) saving_new_entry: bool,
    pub(super) edit_conflict: bool,
    pub(super) revealed_revision: Option<EntryRevision>,
    pub(super) edit_revision: Option<EntryRevision>,
    pub(super) message: Option<String>,
    pub(super) message_until: Option<Instant>,
    pub(super) seconds: u64,
    pub(super) last_operation_status: Option<OperationStatus>,
}

